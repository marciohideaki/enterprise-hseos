/**
 * Commit Message Validator Tests
 *
 * Validates that scripts/governance/validate-commit-msg.sh correctly
 * accepts valid conventional commits and rejects forbidden patterns.
 */

const path = require('node:path');
const { execSync } = require('node:child_process');

const REPO_ROOT = path.join(__dirname, '..');
const VALIDATOR = 'scripts/governance/validate-commit-msg.sh';

function runValidator(msg) {
  try {
    execSync(`"${VALIDATOR}" "${msg}"`, { cwd: REPO_ROOT, stdio: 'pipe', shell: true });
    return { exitCode: 0 };
  } catch (error) {
    return { exitCode: error.status ?? 1 };
  }
}

const cases = [
  {
    description: 'valid conventional commit — fix with scope',
    msg: 'fix(cli): remove broken method',
    expectPass: true,
  },
  {
    description: 'valid conventional commit — feat with scope',
    msg: 'feat(tools): add glob support',
    expectPass: true,
  },
  {
    description: 'no type prefix — plain sentence',
    msg: 'Remove broken method',
    expectPass: false,
  },
  {
    description: 'AI mention in subject',
    msg: 'fix(cli): remove method generated by claude',
    expectPass: false,
  },
  {
    description: 'forbidden Co-Authored-By trailer',
    msg: 'fix(cli): remove method\n\nCo-Authored-By: Someone <x@y.com>',
    expectPass: false,
  },
  {
    description: 'subject longer than 100 characters',
    msg: `fix(cli): ${'x'.repeat(101)}`,
    expectPass: false,
  },
  {
    description: 'allowed identifier — claude-code adapter name',
    msg: 'fix(adapters): wire the claude-code adapter',
    expectPass: true,
  },
  {
    description: 'allowed identifier — .claude/ path',
    msg: 'docs: update .claude/ hooks',
    expectPass: true,
  },
  {
    description: 'allowed identifiers — claude_code, .codex/, plugin dirs',
    msg: 'chore: sync claude_code, .codex/ and .claude-plugin and .codex-plugin',
    expectPass: true,
  },
  {
    description: 'AI mention in prose — vendor name as a word',
    msg: 'feat: add Claude support',
    expectPass: false,
  },
  {
    description: 'AI mention in prose next to an allowed identifier',
    msg: 'fix: claude-code adapter now calls Claude',
    expectPass: false,
  },
  {
    description: 'generated-by phrase',
    msg: 'chore: generated by tool',
    expectPass: false,
  },
  {
    description: 'whole word llm',
    msg: 'fix: llm routing',
    expectPass: false,
  },
  {
    description: 'vendor name in prose — Anthropic',
    msg: 'docs: thanks to Anthropic for the guide',
    expectPass: false,
  },
  {
    description: 'Co-Authored-By trailer naming a tool',
    msg: 'fix(cli): remove method\n\nCo-Authored-By: Tool <noreply@example.com>',
    expectPass: false,
  },
  {
    description: 'term only inside another word — gptr',
    msg: 'fix: gptr',
    expectPass: true,
  },
  {
    description: 'term only inside another word — controllm',
    msg: 'fix: controllm handling',
    expectPass: true,
  },
];

let passed = 0;
let failed = 0;

for (const tc of cases) {
  const { exitCode } = runValidator(tc.msg);
  const succeeded = exitCode === 0;
  const ok = succeeded === tc.expectPass;

  if (ok) {
    console.log(`  PASS  ${tc.description}`);
    passed++;
  } else {
    const got = succeeded ? 'exit 0 (pass)' : `exit ${exitCode} (fail)`;
    const want = tc.expectPass ? 'exit 0 (pass)' : 'exit 1 (fail)';
    console.error(`  FAIL  ${tc.description} — got ${got}, want ${want}`);
    failed++;
  }
}

console.log(`\nCommit message validator tests: ${passed} passed, ${failed} failed`);

if (failed > 0) {
  process.exit(1);
}
